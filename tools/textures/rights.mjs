import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import console from 'node:console';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/**
 * D76 R5: every texture/HDRI file the app ships has a rights record (CC0 source, author, licence, check date, hash).
 * `node tools/textures/rights.mjs check` fails on a missing, stale or extra record; `write` refreshes the hashes of
 * files that already have a source entry (used after tools/textures/prepare_textures.py).
 */
export const SOURCES = {
  wood_oak: { asset: 'WoodFloor051', site: 'ambientCG', author: 'Lennart Demes (ambientCG)' },
  tile_vitrified_600: { asset: 'Marble012', site: 'ambientCG', author: 'Lennart Demes (ambientCG)', derived: 'Original 2x2 tile layout with grout drawn by tools/textures/prepare_textures.py from the marble colour map' },
  marble_white: { asset: 'Marble012', site: 'ambientCG', author: 'Lennart Demes (ambientCG)' },
  plaster: { asset: 'PaintedPlaster017', site: 'ambientCG', author: 'Lennart Demes (ambientCG)', derived: 'Greyscale detail normalised to near white by tools/textures/prepare_textures.py' },
  studio_small_09_1k: { asset: 'studio_small_09', site: 'Poly Haven', author: 'Sergej Majboroda (Poly Haven)' },
};
const SITES = {
  ambientCG: { page: id => `https://ambientcg.com/view?id=${id}`, download: id => `https://ambientcg.com/get?file=${id}_1K-JPG.zip`, licenseUrl: 'https://docs.ambientcg.com/license/' },
  'Poly Haven': { page: id => `https://polyhaven.com/a/${id}`, download: id => `https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/1k/${id}_1k.hdr`, licenseUrl: 'https://polyhaven.com/license' },
};
const FOLDERS = ['apps/web/public/textures', 'apps/web/public/env'];
const RECORDS = 'docs/assets/texture-rights.json';
const files = root => FOLDERS.flatMap(folder => { const out = [], walk = dir => { if (!existsSync(dir)) return; for (const name of readdirSync(dir)) { const path = join(dir, name); if (statSync(path).isDirectory()) walk(path); else out.push(relative(root, path).split(sep).join('/')); } }; walk(join(root, folder)); return out; }).sort();
const sha = (root, path) => createHash('sha256').update(readFileSync(join(root, path))).digest('hex');
const setOf = path => path.startsWith('apps/web/public/env/') ? path.split('/').at(-1).replace(/\.hdr$/, '') : path.split('/').at(-2);

export function expectedRecords(root, checkedOn) {
  return files(root).map(path => {
    const source = SOURCES[setOf(path)];
    if (!source) return { path, problem: 'no source entry' };
    const site = SITES[source.site];
    return { path, set: setOf(path), source: site.page(source.asset), download: site.download(source.asset), license: 'CC0-1.0', licenseUrl: site.licenseUrl, author: source.author, ...source.derived ? { derived: source.derived } : {}, checkedOn, sha256: sha(root, path) };
  });
}
export function checkRights(root) {
  const problems = [], records = existsSync(join(root, RECORDS)) ? JSON.parse(readFileSync(join(root, RECORDS), 'utf8')) : null;
  if (!records || !Array.isArray(records.files)) return [`${RECORDS} is missing or has no "files" list`];
  const byPath = new Map(records.files.map(r => [r.path, r]));
  for (const path of files(root)) {
    const record = byPath.get(path);
    if (!record) { problems.push(`${path} has no rights record`); continue; }
    if (record.license !== 'CC0-1.0' || !record.source || !record.author || !/^\d{4}-\d{2}-\d{2}$/.test(record.checkedOn ?? '')) problems.push(`${path} record is incomplete`);
    if (record.sha256 !== sha(root, path)) problems.push(`${path} does not match its recorded SHA-256`);
  }
  for (const path of byPath.keys()) if (!files(root).includes(path)) problems.push(`${path} is recorded but not shipped`);
  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  if (process.argv[2] === 'write') {
    const checkedOn = process.argv[3] ?? new Date().toISOString().slice(0, 10), records = expectedRecords(root, checkedOn);
    const bad = records.filter(r => r.problem); if (bad.length) { for (const r of bad) console.error(`${r.path}: ${r.problem}`); process.exit(1); }
    writeFileSync(join(root, RECORDS), `${JSON.stringify({ note: 'D76 R5: rights records for shipped textures and HDRIs (CC0). Generated by tools/textures/rights.mjs write; reviewed by hand.', files: records }, null, 2)}\n`);
  }
  const problems = checkRights(root);
  if (problems.length) { for (const p of problems) console.error(`texture rights: ${p}`); process.exit(1); }
  console.log(JSON.stringify({ textureRights: 'ok', files: files(root).length }));
}
